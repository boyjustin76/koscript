"""`word/document.xml` 을 고친다 — **몇 군데를 고쳤는지 세면서.**

양식 문서를 고칠 때 가장 자주 나는 사고는 **엉뚱한 데가 같이 바뀌는 것**이다.
`'댓글에 정리해'` 를 바꾸려다 문서 뒤쪽의 다른 문장까지 바꾼 적이 있다.
그래서 여기서는 **몇 번 찾았는지 세고, 생각한 수와 다르면 멈춘다.**

빈 칸(공백만 든 칸)은 문자열로 못 짚는다 → `칸바꾸기` 로 번호를 짚는다.
"""
import re

from . import read as _읽기


def 한번만(본문xml, 옛, 새):
    """`옛` 이 정확히 한 번 나올 때만 바꾼다. 아니면 멈춘다."""
    n = 본문xml.count(옛)
    if n != 1:
        raise ValueError('%d 번 찾았다 (한 번이어야 한다): %r' % (n, 옛[:70]))
    return 본문xml.replace(옛, 새)


def 여러번(본문xml, 바꿈들):
    """[(옛, 새)] 를 차례로. 하나라도 한 번이 아니면 **아무것도 안 바꾸고** 멈춘다."""
    s = 본문xml
    for 옛, 새 in 바꿈들:
        s = 한번만(s, 옛, 새)
    return s


def 문단바꾸기(본문xml, 번호, 새문단xml):
    """`read.문단들` 의 번호로 문단 하나를 통째로 갈아 끼운다.

    런이 잘게 쪼개져 문자열로 못 짚을 때 쓴다. 여는 태그와 `<w:pPr>` 는
    `머리따기` 로 원래 것을 가져다 쓰면 양식이 안 깨진다.
    """
    옛 = _읽기.문단들(본문xml)[번호]
    return 한번만(본문xml, 옛, 새문단xml)


def 머리따기(문단xml):
    """문단의 여는 태그 + `<w:pPr>` — 새로 지을 때 양식을 그대로 물려받으려고."""
    m = re.match(r'(<w:p\b[^>]*>)(<w:pPr>.*?</w:pPr>)?', 문단xml, re.S)
    return m.group(1) + (m.group(2) or '')


def 지킴(본문xml, 없어야=(), 있어야=()):
    """고친 뒤 거는 빗장. 지웠어야 할 말이 남았거나 넣었어야 할 말이 없으면 멈춘다."""
    글 = '\n'.join(_읽기.줄들(본문xml))
    남은 = [말 for 말 in 없어야 if 말 in 글]
    빠진 = [말 for 말 in 있어야 if 말 not in 글]
    if 남은 or 빠진:
        raise ValueError('남은 말 %r · 빠진 말 %r' % (남은, 빠진))
    return True
